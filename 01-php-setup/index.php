<?php

declare(strict_types=1);

/**
 * Урок 01 — Как установить PHP и что такое веб-серверы.
 *
 * Этот файл — не столько про синтаксис PHP, сколько про то,
 * что происходит «под капотом», когда браузер обращается
 * к PHP-скрипту через веб-сервер (Apache в составе XAMPP).
 *
 * Открой этот файл в браузере по адресу:
 * http://localhost/php-the-right-way/01-php-setup/
 */

// ---------------------------------------------------------------------
// 1. Самая первая программа.
// Это ровно то, что автор показывает в начале курса.
// ---------------------------------------------------------------------

echo 'Hello world';

/*
    Тег <?php ... ?> — граница между HTML и PHP.
    Всё, что вне тега, браузер получит как обычный HTML.
*/


// ---------------------------------------------------------------------
// 2. Проверяем, что PHP установлен и работает.
// phpversion() возвращает текущую версию интерпретатора PHP.
// ---------------------------------------------------------------------

echo '<br>';
echo 'Версия PHP: ' . phpversion();


// ---------------------------------------------------------------------
// 3. Проверяем, что запрос пришёл через веб-сервер, а не через CLI.
// PHP_SAPI — это «интерфейс», через который PHP общается с окружением.
// Для Apache это обычно "apache2handler", для Nginx+PHP-FPM — "fpm-fcgi",
// для запуска из терминала (php index.php) — "cli".
// ---------------------------------------------------------------------

echo '<br>';
echo 'SAPI: ' . PHP_SAPI;


// ---------------------------------------------------------------------
// 4. Смотрим, какой веб-сервер обслуживает запрос и на каком порту.
// Эти данные лежат в суперглобальном массиве $_SERVER.
// Мы разберём его подробно в следующих уроках, но здесь — первое касание.
// ---------------------------------------------------------------------

echo '<br>';
echo 'Программное обеспечение сервера: ' . ($_SERVER['SERVER_SOFTWARE'] ?? 'неизвестно');

echo '<br>';
echo 'Порт: ' . ($_SERVER['SERVER_PORT'] ?? 'неизвестно');

echo '<br>';
echo 'Имя хоста: ' . ($_SERVER['SERVER_NAME'] ?? 'неизвестно');


// ---------------------------------------------------------------------
// 5. Корень документа — папка, которую Apache считает «стартовой».
// Именно сюда Apache смотрит, когда получает запрос.
// У нас это C:\xampp\htdocs.
// ---------------------------------------------------------------------

echo '<br>';
echo 'Document Root: ' . ($_SERVER['DOCUMENT_ROOT'] ?? 'неизвестно');


// ---------------------------------------------------------------------
// 6. Сценарий, который сейчас выполняется, и метод запроса.
// ---------------------------------------------------------------------

echo '<br>';
echo 'Выполняется файл: ' . ($_SERVER['SCRIPT_FILENAME'] ?? 'неизвестно');

echo '<br>';
echo 'Метод запроса: ' . ($_SERVER['REQUEST_METHOD'] ?? 'неизвестно');


// ---------------------------------------------------------------------
// 7. Демонстрация HTTP-кодов состояния.
//
// По умолчанию PHP отправляет клиенту код 200 (OK), если ничего
// не сломано. Но код можно задать вручную через http_response_code().
// Раскомментируй одну из строк ниже и обнови страницу — браузер
// отреагирует соответствующим образом.
// ---------------------------------------------------------------------

// http_response_code(404);   // Страница не найдена
// http_response_code(500);   // Внутренняя ошибка сервера
// http_response_code(301);   // Постоянное перенаправление

echo '<br>';
echo 'HTTP-код ответа: ' . http_response_code();


// ---------------------------------------------------------------------
// 8. Разделитель для читаемости вывода в браузере.
// ---------------------------------------------------------------------

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;