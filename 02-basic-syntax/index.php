<?php

declare(strict_types=1);

/**
 * Урок 02 — Базовый синтаксис PHP.
 *
 * Практика: теги PHP, echo, print, переменные, ссылки,
 * кавычки, конкатенация, комментарии.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/02-basic-syntax/
 */

/*
    ---------------------------------------------------------------------
    1. Первый вывод. Теги PHP.
    Всё, что вне <?php ... ?>, PHP игнорирует.
    ---------------------------------------------------------------------
*/

echo 'Hello World';
echo '<br>';

// ---------------------------------------------------------------------
// 2. Одинарные vs двойные кавычки.
// В одинарных переменные не подставляются.
// В двойных — подставляются.
// ---------------------------------------------------------------------

$name = 'Gio';

echo 'Одинарные: Hello, $name';       // выведет: Hello, $name
echo '<br>';

echo "Двойные: Hello, $name";         // выведет: Hello, Gio
echo '<br>';

// Фигурные скобки для читаемости при сложных выражениях.
echo "Фигурные: Hello, {$name}!";
echo '<br>';

// Альтернативный вариант применения фигурных скобок для читаемости при сложных выражениях.
echo "Фигурные: Hello, ${name}!";   # Этот синтаксис интерполяции ${var} объявлен устаревшим (deprecated в PHP 8.3).
echo '<br>';

// ---------------------------------------------------------------------
// 3. Конкатенация через точку.
// ---------------------------------------------------------------------

echo 'Склейка: ' . 'Hello' . ' ' . 'World';
echo '<br>';

// ---------------------------------------------------------------------
// 4. echo vs print.
// print возвращает 1, echo — ничего.
// ---------------------------------------------------------------------

echo 'echo не возвращает значение.';
echo '<br>';

$result = print 'print возвращает 1.';
echo '<br>';
var_dump($result);   // int(1)
echo '<br>';

// echo принимает несколько аргументов через запятую.
echo 'Первый', ' ', 'Второй', ' ', 'Третий';
echo '<br>';

// ---------------------------------------------------------------------
// 5. Переменные: присваивание по значению.
// $b — копия $a. Изменение $a не влияет на $b.
// ---------------------------------------------------------------------

$a = 10;
$b = $a;
$a = 20;

echo "По значению: \$a = $a, \$b = $b";
echo '<br>';

// ---------------------------------------------------------------------
// 6. Переменные: присваивание по ссылке.
// $c — ссылка на $a. Изменение $a влияет на $c.
// ---------------------------------------------------------------------

$a = 10;
$c = &$a;
$a = 20;

echo "По ссылке: \$a = $a, \$c = $c";
echo '<br>';

// ---------------------------------------------------------------------
// 7. Комментарии.
// ---------------------------------------------------------------------

// Это однострочный комментарий через //

# Это тоже однострочный комментарий, через #

/*
 * Это многострочный комментарий.
 * Он может занимать несколько строк.
 */

echo 'Комментарии не выводятся в браузер.';
echo '<br>';

// ---------------------------------------------------------------------
// 8. Отладка: var_dump() и print_r().
// var_dump показывает тип и значение.
// print_r — более читаемый, но менее информативный.
// ---------------------------------------------------------------------

$string = 'Hello';
$number = 42;
$float = 3.14;
$bool = true;
$null = null;

echo '<pre>';
var_dump($string);
var_dump($number);
var_dump($float);
var_dump($bool);
var_dump($null);
echo '</pre>';

// print_r удобен для массивов (разберём в уроке 10).
$array = ['apple', 'banana', 'cherry'];

echo '<pre>';
print_r($array);
echo '</pre>';

// ---------------------------------------------------------------------
// 9. Проверка типов через gettype().
// ---------------------------------------------------------------------

echo 'Тип $string: ' . gettype($string) . '<br>';
echo 'Тип $number: ' . gettype($number) . '<br>';
echo 'Тип $float: ' . gettype($float) . '<br>';
echo 'Тип $bool: ' . gettype($bool) . '<br>';
echo 'Тип $null: ' . gettype($null) . '<br>';

// ---------------------------------------------------------------------
// 10. Константа PHP_VERSION — всегда доступна.
// ---------------------------------------------------------------------

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;