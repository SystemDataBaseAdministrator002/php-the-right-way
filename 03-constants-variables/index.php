<?php

declare(strict_types=1);

/**
 * Урок 03 — Константы и переменные переменные.
 *
 * Практика: define(), const, defined(), constant(),
 * магические константы, переменные переменные.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/03-constants-variables/
 */

// ---------------------------------------------------------------------
// 1. Определение константы через define().
// define() вычисляется в рантайме, поэтому может принимать переменные.
// ---------------------------------------------------------------------

$paid = 'paid';
define('CONSTANT_PAID', $paid);

echo 'define: ' . CONSTANT_PAID;   // paid
echo '<br>';

// ---------------------------------------------------------------------
// 2. Определение константы через const.
// const вычисляется на этапе компиляции, поэтому переменные использовать нельзя.
// ---------------------------------------------------------------------

const CONSTANT_VAR = 'var';

echo 'const: ' . CONSTANT_VAR;   // var
echo '<br>';

// ---------------------------------------------------------------------
// 3. Проверка существования константы.
// ---------------------------------------------------------------------

if (defined('CONSTANT_PAID')) {
    echo 'CONSTANT_PAID определена.';
} else {
    echo 'CONSTANT_PAID не определена.';
}
echo '<br>';

// ---------------------------------------------------------------------
// 4. Чтение константы по динамическому имени.
// constant() позволяет получить значение, если имя хранится в переменной.
// ---------------------------------------------------------------------

$constName = 'CONSTANT_VAR';
echo 'constant(): ' . constant($constName);   // var
echo '<br>';

// ---------------------------------------------------------------------
// 5. Переменные переменные.
// $$foo создаёт переменную, имя которой равно значению $foo.
// ---------------------------------------------------------------------

$foo = 'bar';
$$foo = 'baz';   // создаётся $bar со значением 'baz'

echo '$foo = ' . $foo;     // bar
echo '<br>';
echo '$bar = ' . $bar;     // baz
echo '<br>';

// Явная демонстрация через ${$foo} — то же самое, но читается яснее.
echo '${$foo} = ' . ${$foo};   // baz
echo '<br>';

// ---------------------------------------------------------------------
// 6. Магические константы.
// ---------------------------------------------------------------------

echo 'Текущая строка: ' . __LINE__;
echo '<br>';
echo 'Текущий файл: ' . __FILE__;
echo '<br>';
echo 'Директория: ' . __DIR__;
echo '<br>';

// ---------------------------------------------------------------------
// 7. Предопределённая константа PHP_VERSION.
// ---------------------------------------------------------------------

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;