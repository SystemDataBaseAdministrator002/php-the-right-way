<?php

declare(strict_types=1);

/**
 * Урок 14 — Приоритет и ассоциативность операторов.
 *
 * Практика: приоритет, скобки, ассоциативность,
 * логические операторы, and vs &&, ??.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/14-operator-precedence/
 */

// ---------------------------------------------------------------------
// 1. Приоритет арифметических операторов.
// ---------------------------------------------------------------------

echo '<h3>1. Приоритет арифметики</h3>';

$x = 5 + 3 * 5;
echo '5 + 3 * 5 = ' . $x . '<br>';         // 20

$y = (5 + 3) * 5;
echo '(5 + 3) * 5 = ' . $y . '<br>';       // 40

// Вложенные скобки.
$z = 2 * (3 + (4 * 5));
echo '2 * (3 + (4 * 5)) = ' . $z . '<br>'; // 46

// ---------------------------------------------------------------------
// 2. Ассоциативность (левая).
// ---------------------------------------------------------------------

echo '<h3>2. Левая ассоциативность</h3>';

$result = 10 / 2 * 3;
echo '10 / 2 * 3 = ' . $result . '<br>';   // 15

// ---------------------------------------------------------------------
// 3. Ассоциативность (правая).
// ---------------------------------------------------------------------

echo '<h3>3. Правая ассоциативность</h3>';

$a = $b = 5;
echo "\$a = $a, \$b = $b<br>";   // 5, 5

// Возведение в степень.
$power = 2 ** 3 ** 2;
echo '2 ** 3 ** 2 = ' . $power . '<br>';   // 512 (2 ** (3 ** 2))

// ---------------------------------------------------------------------
// 4. Логические операторы.
// ---------------------------------------------------------------------

echo '<h3>4. Логические операторы</h3>';

$x = true || false && false;
var_dump($x);   // true (&& выше ||)
echo '<br>';

$y = (true || false) && false;
var_dump($y);   // false
echo '<br>';

// Приоритет ! (высокий).
var_dump(!true && false);    // false
var_dump(!(true && false));  // true
echo '<br>';

// ---------------------------------------------------------------------
// 5. and vs &&.
// ---------------------------------------------------------------------

echo '<h3>5. and vs &&</h3>';
echo '<pre>';

$a = 5;
$b = 10;
$z = $a = 5 and $b = 10;

echo "\$a = $a, \$b = $b, \$z = $z\n";   // 5, 10, 5

$a = 5;
$b = 10;
$w = $a = 5 && $b = 10;

echo "\$a = $a, \$b = $b, \$w = " . var_export($w, true) . "\n";   // 5, 10, true

echo '</pre>';

// ---------------------------------------------------------------------
// 6. Тернарный оператор (неассоциативен в PHP 8).
// ---------------------------------------------------------------------

echo '<h3>6. Тернарный оператор</h3>';

$age = 20;

// $result = $age < 18 ? 'child' : $age < 65 ? 'adult' : 'senior'; // Fatal error

// Правильно:
$result = $age < 18 ? 'child' : ($age < 65 ? 'adult' : 'senior');
echo 'Категория: ' . $result . '<br>';   // adult

// ---------------------------------------------------------------------
// 7. Оператор ?? (правоассоциативен).
// ---------------------------------------------------------------------

echo '<h3>7. Оператор ??</h3>';

$a = null;
$b = null;
$c = 'value';

$result = $a ?? $b ?? $c;
echo 'Результат: ' . $result . '<br>';   // value

// ---------------------------------------------------------------------
// 8. Приоритет . в PHP 8.
// ---------------------------------------------------------------------

echo '<h3>8. Приоритет . в PHP 8</h3>';

try {
    echo 'Result: ' . 1 + 2;
} catch (TypeError $e) {
    echo 'TypeError: ' . $e->getMessage() . '<br>';
}

echo 'Правильно: ' . 'Result: ' . (1 + 2) . '<br>';   // Result: 3

// ---------------------------------------------------------------------
// 9. Скобки для ясности.
// ---------------------------------------------------------------------

echo '<h3>9. Скобки для ясности</h3>';

$total = (10 + 5) * (3 - 1);
echo '(10 + 5) * (3 - 1) = ' . $total . '<br>';   // 30

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;