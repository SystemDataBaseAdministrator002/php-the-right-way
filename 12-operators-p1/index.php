<?php

declare(strict_types=1);

/**
 * Урок 12 — Операторы (часть 1).
 *
 * Практика: арифметические, присваивания, сравнения,
 * логические, тернарный, ??, <=>.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/12-operators-p1/
 */

// ---------------------------------------------------------------------
// 1. Арифметические операторы.
// ---------------------------------------------------------------------

echo '<h3>1. Арифметические</h3>';
$x = 10;
$y = 3;

echo '<pre>';
var_dump($x + $y);    // 13
var_dump($x - $y);    // 7
var_dump($x * $y);    // 30
var_dump($x / $y);    // 3.333...
var_dump($x % $y);    // 1
var_dump($x ** $y);   // 1000
echo '</pre>';

// Деление нацело и float.
echo '10 / 2 = ';
var_dump(10 / 2);     // int(5)

echo '10 / 3 = ';
var_dump(10 / 3);     // float(3.333...)

// ---------------------------------------------------------------------
// 2. Деление на ноль и fdiv.
// ---------------------------------------------------------------------

echo '<h3>2. Деление на ноль</h3>';

try {
    $result = 1 / 0;
} catch (DivisionByZeroError $e) {
    echo 'DivisionByZeroError: ' . $e->getMessage() . '<br>';
}

echo 'fdiv(1, 0) = ';
var_dump(fdiv(1, 0));   // INF

echo 'fdiv(0, 0) = ';
var_dump(fdiv(0, 0));   // NAN

// ---------------------------------------------------------------------
// 3. Модуль и знак.
// ---------------------------------------------------------------------

echo '<h3>3. Модуль</h3>';
echo '<pre>';
var_dump(10 % 3);    // 1
var_dump(-10 % 3);   // -1
var_dump(10 % -3);   // 1
echo '</pre>';

// ---------------------------------------------------------------------
// 4. Целочисленное деление.
// ---------------------------------------------------------------------

echo '<h3>4. intdiv</h3>';
var_dump(intdiv(10, 3));   // 3
echo '<br>';

// ---------------------------------------------------------------------
// 5. Переполнение.
// ---------------------------------------------------------------------

echo '<h3>5. Переполнение</h3>';
var_dump(PHP_INT_MAX + 1);   // float
echo '<br>';

// ---------------------------------------------------------------------
// 6. Присваивание и комбинированные операторы.
// ---------------------------------------------------------------------

echo '<h3>6. Присваивание</h3>';

$a = 5;
$b = $a = 10;
echo "\$a = $a, \$b = $b<br>";   // 10, 10

$c = ($a = 5) + 2;
echo "\$a = $a, \$c = $c<br>";   // 5, 7

$count = 0;
$count += 5;
echo '$count += 5 → ' . $count . '<br>';   // 5
$count -= 2;
echo '$count -= 2 → ' . $count . '<br>';   // 3
$count *= 2;
echo '$count *= 2 → ' . $count . '<br>';   // 6

// ??=
$arr = [];
$arr['key'] ??= 'default';
echo '$arr["key"] = ' . $arr['key'] . '<br>';   // default

// ---------------------------------------------------------------------
// 7. Сравнение.
// ---------------------------------------------------------------------

echo '<h3>7. Сравнение</h3>';
echo '<pre>';

var_dump(1 == "1");     // true (с приведением)
var_dump(1 === "1");    // false (разные типы)
var_dump(0 == "abc");   // false (строковое сравнение в PHP 8)
var_dump("1" == "01");  // true (числовое)

var_dump(1 <=> 2);   // -1
var_dump(2 <=> 2);   // 0
var_dump(3 <=> 2);   // 1

echo '</pre>';

// ---------------------------------------------------------------------
// 8. Логические операторы.
// ---------------------------------------------------------------------

echo '<h3>8. Логические</h3>';
echo '<pre>';

var_dump(true && false);   // false
var_dump(true || false);   // true
var_dump(!true);           // false

var_dump(true and false);  // false
var_dump(true or false);   // true
var_dump(true xor true);   // false
var_dump(true xor false);  // true

// Приоритет: && выше, чем and.
$a = true && false;
$b = true and false;

var_dump($a);   // false
var_dump($b);   // true — потому что and ниже, чем =

echo '</pre>';

// ---------------------------------------------------------------------
// 9. Тернарный оператор.
// ---------------------------------------------------------------------

echo '<h3>9. Тернарный</h3>';

$isPaid = true;
$status = $isPaid ? 'paid' : 'unpaid';
echo 'Статус: ' . $status . '<br>';   // paid

// Вложенный тернарный — обязательно со скобками в PHP 8.
$age = 20;
$category = $age < 18 ? 'child' : ($age < 65 ? 'adult' : 'senior');
echo 'Категория: ' . $category . '<br>';   // adult

// ---------------------------------------------------------------------
// 10. Оператор ??.
// ---------------------------------------------------------------------

echo '<h3>10. Оператор ??</h3>';

$_GET['user'] = 'Gio';
$username = $_GET['user'] ?? 'guest';
echo 'username: ' . $username . '<br>';   // Gio

$missing = $_GET['missing'] ?? 'default';
echo 'missing: ' . $missing . '<br>';     // default

// Цепочка.
$value = null ?? null ?? 'fallback';
echo 'value: ' . $value . '<br>';         // fallback

// ---------------------------------------------------------------------
// 11. ?? vs ?:.
// ---------------------------------------------------------------------

echo '<h3>11. ?? vs ?:</h3>';
echo '<pre>';

$var = '';

var_dump($var ?? 'default');   // string(0) ""
var_dump($var ?: 'default');   // string(7) "default"

$var = null;

var_dump($var ?? 'default');   // string(7) "default"
var_dump($var ?: 'default');   // string(7) "default"

echo '</pre>';

// ---------------------------------------------------------------------
// 12. Приоритет конкатенации в PHP 8.
// ---------------------------------------------------------------------

echo '<h3>12. Приоритет . в PHP 8</h3>';

// PHP 7: 'Result: ' . (1 + 2) = 'Result: 3'
// PHP 8: ('Result: ' . 1) + 2 — TypeError
try {
    echo 'Result: ' . 1 + 2;
} catch (TypeError $e) {
    echo 'TypeError: ' . $e->getMessage() . '<br>';
}

// Правильно:
echo 'Result: ' . (1 + 2) . '<br>';   // Result: 3

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;