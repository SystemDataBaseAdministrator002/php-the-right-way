<?php

declare(strict_types=1);

/**
 * Урок 04 — Типы данных и приведение типов.
 *
 * Практика: 10 примитивных типов, gettype() vs get_debug_type(),
 * var_dump() vs print_r(), явное и неявное приведение.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/04-data-types-casting/
 */

// ---------------------------------------------------------------------
// 1. Все скалярные типы.
// ---------------------------------------------------------------------

$bool   = true;
$int    = 42;
$float  = 3.14;
$string = 'Hello';

// ---------------------------------------------------------------------
// 2. Составные типы.
// ---------------------------------------------------------------------

$array    = [1, 2, 3];
$object   = new stdClass();
$callable = 'strlen';          // имя функции как строка

// ---------------------------------------------------------------------
// 3. Особые типы.
// ---------------------------------------------------------------------

$null = null;

// resource нельзя создать вручную, только через функцию.
$resource = fopen('php://memory', 'r');

// ---------------------------------------------------------------------
// 4. gettype() vs get_debug_type().
// gettype() возвращает исторические имена: "integer", "double".
// get_debug_type() возвращает канонические: "int", "float".
// ---------------------------------------------------------------------

echo '<h3>gettype() vs get_debug_type()</h3>';
echo '<pre>';

foreach ([$bool, $int, $float, $string, $array, $object, $callable, $null] as $value) {
    printf(
        "gettype: %-10s | get_debug_type: %-10s\n",
        gettype($value),
        get_debug_type($value)
    );
}

echo '</pre>';

// ---------------------------------------------------------------------
// 5. var_dump() vs print_r().
// ---------------------------------------------------------------------

echo '<h3>var_dump() vs print_r()</h3>';

echo '<pre>';
echo "var_dump(\$array):\n";
var_dump($array);

echo "\nprint_r(\$array):\n";
print_r($array);
echo '</pre>';

// ---------------------------------------------------------------------
// 6. Явное приведение типов (explicit cast).
// ---------------------------------------------------------------------

echo '<h3>Явное приведение</h3>';
echo '<pre>';

var_dump((int) '123');      // int(123)
var_dump((int) '123abc');   // int(123)
var_dump((int) 'abc123');   // int(0)
var_dump((float) '12.5');   // float(12.5)
var_dump((string) 42);      // string(2) "42"
var_dump((bool) 0);         // bool(false)
var_dump((bool) '0');       // bool(false)
var_dump((bool) '0.0');     // bool(true) — непустая строка
var_dump((bool) '');        // bool(false)
var_dump((bool) []);        // bool(false)

echo '</pre>';

// ---------------------------------------------------------------------
// 7. Неявное приведение (type juggling).
// ---------------------------------------------------------------------

echo '<h3>Неявное приведение (type juggling)</h3>';
echo '<pre>';

var_dump(1 + '2');          // int(3)
var_dump('10' + '5');       // int(15)
var_dump('1.5' + 1);        // float(2.5)
var_dump(1 . '2');          // string(2) "12" (конкатенация)
var_dump('abc' == 0);       // bool(false) — начиная с PHP 8.0

echo '</pre>';

// ---------------------------------------------------------------------
// 8. Строгий режим.
// strict_types=1 включён в начале файла.
// Следующая функция принимает только int.
// ---------------------------------------------------------------------

echo '<h3>Строгий режим</h3>';

function add(int $a, int $b): int
{
    return $a + $b;
}

echo 'add(1, 2) = ' . add(1, 2) . '<br>';

// Раскомментируй строки ниже — увидишь TypeError:
// add(1.5, 2);     // TypeError: must be of type int, float given
// add("1", 2);     // TypeError: must be of type int, string given

// ---------------------------------------------------------------------
// 9. Закрываем ресурс.
// ---------------------------------------------------------------------

fclose($resource);

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;