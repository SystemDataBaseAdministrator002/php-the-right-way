<?php

declare(strict_types=1);

/**
 * Урок 24 — Анонимные функции, замыкания, стрелочные функции.
 *
 * Практика: переменные функции, use, захват по значению и ссылке,
 * стрелочные функции, callable, first-class callable.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/24-closures-arrow-functions/
 */

// ---------------------------------------------------------------------
// 1. Переменные функции.
// ---------------------------------------------------------------------

echo '<h3>1. Переменные функции</h3>';

function greet(string $name): string
{
    return "Hello, $name";
}

$fn = 'greet';
echo $fn('Gio') . '<br>';   // Hello, Gio

var_dump(is_callable($fn));   // true
echo '<br>';

// Языковые конструкции не работают:
$echo = 'echo';
// $echo('Hello');   // Fatal error

// Обёртка:
function my_echo(string $s): void { echo $s; }
$myEcho = 'my_echo';
$myEcho('Hello via wrapper<br>');

// ---------------------------------------------------------------------
// 2. Анонимные функции.
// ---------------------------------------------------------------------

echo '<h3>2. Анонимные функции</h3>';

$greetAnon = function (string $name): string {
    return "Hi, $name";
};

echo $greetAnon('Gio') . '<br>';   // Hi, Gio

// ---------------------------------------------------------------------
// 3. Замыкания: захват по значению.
// ---------------------------------------------------------------------

echo '<h3>3. Захват по значению</h3>';

$counter = 0;

$increment = function () use ($counter) {
    $counter++;
    echo 'Внутри: ' . $counter . '<br>';
};

$increment();   // Внутри: 1
echo 'Снаружи: ' . $counter . '<br>';   // Снаружи: 0

// ---------------------------------------------------------------------
// 4. Замыкания: захват по ссылке.
// ---------------------------------------------------------------------

echo '<h3>4. Захват по ссылке</h3>';

$counter = 0;

$incrementRef = function () use (&$counter) {
    $counter++;
    echo 'Внутри: ' . $counter . '<br>';
};

$incrementRef();   // Внутри: 1
echo 'Снаружи: ' . $counter . '<br>';   // Снаружи: 1

// ---------------------------------------------------------------------
// 5. Момент захвата.
// ---------------------------------------------------------------------

echo '<h3>5. Момент захвата</h3>';

$x = 10;
$fnCapture = function () use ($x) { return $x; };
$x = 20;
echo 'Захвачено: ' . $fnCapture() . '<br>';   // 10

// ---------------------------------------------------------------------
// 6. Стрелочные функции.
// ---------------------------------------------------------------------

echo '<h3>6. Стрелочные функции</h3>';

$double = fn($x) => $x * 2;
echo 'double(5) = ' . $double(5) . '<br>';   // 10

// Автоматический захват.
$factor = 3;
$multiply = fn($x) => $x * $factor;
echo 'multiply(5) = ' . $multiply(5) . '<br>';   // 15

// ---------------------------------------------------------------------
// 7. Стрелочные функции в array_map/filter.
// ---------------------------------------------------------------------

echo '<h3>7. Стрелочные в array_map/filter</h3>';

$numbers = [1, 2, 3, 4, 5];

$squared = array_map(fn($n) => $n * $n, $numbers);
echo 'squared: ' . implode(', ', $squared) . '<br>';   // 1, 4, 9, 16, 25

$even = array_filter($numbers, fn($n) => $n % 2 === 0);
echo 'even: ' . implode(', ', $even) . '<br>';         // 2, 4

// ---------------------------------------------------------------------
// 8. Callback и callable.
// ---------------------------------------------------------------------

echo '<h3>8. Callback</h3>';

function apply(callable $fn, mixed $value): mixed
{
    return $fn($value);
}

echo apply('strtoupper', 'hello') . '<br>';   // HELLO
echo apply(fn($x) => $x * 2, 5) . '<br>';     // 10

// ---------------------------------------------------------------------
// 9. First-class callable syntax (PHP 8.1+).
// ---------------------------------------------------------------------

echo '<h3>9. First-class callable</h3>';

$strlen = strlen(...);
$upper = strtoupper(...);

echo '$strlen("Hello") = ' . $strlen('Hello') . '<br>';   // 5
echo '$upper("hello") = ' . $upper('hello') . '<br>';     // HELLO

// ---------------------------------------------------------------------
// 10. $this в замыканиях.
// ---------------------------------------------------------------------

echo '<h3>10. $this в замыканиях</h3>';

class Foo
{
    private string $bar = 'baz';

    public function getClosure(): Closure
    {
        return function () {
            return $this->bar;
        };
    }
}

$foo = new Foo();
$closure = $foo->getClosure();
echo 'Закрытие: ' . $closure() . '<br>';   // baz

// ---------------------------------------------------------------------
// 11. static-замыкание.
// ---------------------------------------------------------------------

echo '<h3>11. static-замыкание</h3>';

$staticFn = static function () {
    return 'static closure';
};

echo $staticFn() . '<br>';

// ---------------------------------------------------------------------
// 12. Возврат замыкания.
// ---------------------------------------------------------------------

echo '<h3>12. Возврат замыкания</h3>';

function multiplier(int $factor): Closure
{
    return fn($n) => $n * $factor;
}

$triple = multiplier(3);
echo 'triple(5) = ' . $triple(5) . '<br>';   // 15

// ---------------------------------------------------------------------
// 13. use с трейлинг-запятой (PHP 8.0+).
// ---------------------------------------------------------------------

echo '<h3>13. use с трейлинг-запятой</h3>';

$a = 1;
$b = 2;

$fnTrailing = function () use ($a, $b,) {
    return $a + $b;
};

echo $fnTrailing() . '<br>';   // 3

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;