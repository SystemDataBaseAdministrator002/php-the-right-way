<?php

declare(strict_types=1);

/**
 * Урок 15 — Условные операторы if, else, elseif.
 *
 * Практика: if, else, elseif, вложенные условия,
 * альтернативный синтаксис, тернарный оператор.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/15-control-structures-if-else/
 */

// ---------------------------------------------------------------------
// 1. Простой if.
// ---------------------------------------------------------------------

echo '<h3>1. Простой if</h3>';

$isPaid = true;

if ($isPaid) {
    echo 'Заказ оплачен.<br>';
}

// Без фигурных скобок (не рекомендуется):
if ($isPaid)
    echo 'Оплачен (без скобок).<br>';

// ---------------------------------------------------------------------
// 2. if-else.
// ---------------------------------------------------------------------

echo '<h3>2. if-else</h3>';

$age = 20;

if ($age >= 18) {
    echo 'Совершеннолетний.<br>';
} else {
    echo 'Несовершеннолетний.<br>';
}

// ---------------------------------------------------------------------
// 3. elseif.
// ---------------------------------------------------------------------

echo '<h3>3. elseif</h3>';

$score = 85;

if ($score >= 90) {
    echo 'Оценка: A<br>';
} elseif ($score >= 80) {
    echo 'Оценка: B<br>';
} elseif ($score >= 70) {
    echo 'Оценка: C<br>';
} else {
    echo 'Оценка: F<br>';
}

// ---------------------------------------------------------------------
// 4. Вложенные условия.
// ---------------------------------------------------------------------

echo '<h3>4. Вложенные условия</h3>';

$user = [
    'name' => 'Gio',
    'isAdmin' => true,
];

if ($user) {
    if ($user['isAdmin']) {
        echo 'Админ: ' . $user['name'] . '<br>';
    } else {
        echo 'Пользователь: ' . $user['name'] . '<br>';
    }
}

// ---------------------------------------------------------------------
// 5. Условие как выражение.
// ---------------------------------------------------------------------

echo '<h3>5. Условие как выражение</h3>';

$count = 0;

if ($count) {
    echo 'Есть элементы.<br>';
} else {
    echo 'Пусто.<br>';
}

$arr = [];
if (count($arr)) {
    echo 'Массив не пуст.<br>';
} else {
    echo 'Массив пуст.<br>';
}

// ---------------------------------------------------------------------
// 6. elseif vs else if (обычный синтаксис).
// ---------------------------------------------------------------------

echo '<h3>6. elseif vs else if</h3>';

$a = false;
$b = true;

if ($a) {
    echo 'A<br>';
} elseif ($b) {
    echo 'B (elseif)<br>';
}

if ($a) {
    echo 'A<br>';
} else if ($b) {
    echo 'B (else if)<br>';
}

// ---------------------------------------------------------------------
// 7. Тернарный оператор.
// ---------------------------------------------------------------------

echo '<h3>7. Тернарный оператор</h3>';

$isPaid = false;
$status = $isPaid ? 'paid' : 'unpaid';
echo 'Статус: ' . $status . '<br>';

// ---------------------------------------------------------------------
// 8. Альтернативный синтаксис.
// ---------------------------------------------------------------------

echo '<h3>8. Альтернативный синтаксис</h3>';

$isAdmin = true;
?>

<div class="user-card">
    <?php if ($isAdmin): ?>
        <p>Панель администратора</p>
    <?php else: ?>
        <p>Обычная страница</p>
    <?php endif; ?>
</div>

<?php
// ---------------------------------------------------------------------
// 9. Альтернативный синтаксис с elseif.
// ---------------------------------------------------------------------

echo '<h3>9. Альтернативный синтаксис с elseif</h3>';

$userStatus = 'online';
?>

<div class="status">
    <?php if ($userStatus === 'online'): ?>
        <span class="online">Онлайн</span>
    <?php elseif ($userStatus === 'recent'): ?>
        <span class="recent">Был недавно</span>
    <?php else: ?>
        <span class="offline">Офлайн</span>
    <?php endif; ?>
</div>

<?php
// ---------------------------------------------------------------------
// 10. Практический пример: система оценивания.
// ---------------------------------------------------------------------

echo '<h3>10. Система оценивания</h3>';

$scores = [95, 85, 75, 65];

foreach ($scores as $score) {
    if ($score >= 90) {
        $grade = 'A';
    } elseif ($score >= 80) {
        $grade = 'B';
    } elseif ($score >= 70) {
        $grade = 'C';
    } else {
        $grade = 'F';
    }

    echo "Балл: $score → Оценка: $grade<br>";
}

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;