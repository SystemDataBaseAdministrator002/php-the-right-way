<?php

declare(strict_types=1);

/**
 * Урок 08 — Строки: Heredoc и Nowdoc.
 *
 * Практика: создание строк, интерполяция, доступ к символам,
 * Heredoc, Nowdoc, основные функции.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/08-string-heredoc-nowdoc/
 */

// ---------------------------------------------------------------------
// 1. Создание строк.
// ---------------------------------------------------------------------

$single = 'Hello, $name';
$double = "Hello, $name";
$name = 'Gio';

echo '<h3>1. Создание строк</h3>';
echo 'Одинарные: ' . $single . '<br>';    // Hello, $name
echo 'Двойные: '  . "Hello, $name" . '<br>'; // Hello, Gio
echo 'Фигурные: ' . "Hello, {$name}" . '<br>'; // Hello, Gio

// ---------------------------------------------------------------------
// 2. Доступ к символам.
// ---------------------------------------------------------------------

echo '<h3>2. Доступ к символам</h3>';
$str = 'Hello';

echo '$str[0] = ' . $str[0] . '<br>';    // H
echo '$str[4] = ' . $str[4] . '<br>';    // o
echo '$str[-1] = ' . $str[-1] . '<br>';  // o (PHP 7.1+)

// Изменение строки посимвольно.
$str[0] = 'J';
echo 'После $str[0] = "J": ' . $str . '<br>';   // Jello

// Чтение за пределами строки — Warning, возвращает "".
// Раскомментируй — увидишь Warning:
// echo $str[100];

// Запись за пределами строки — дополняется пробелами.
$str2 = 'Hi';
$str2[5] = '!';
echo 'Запись за пределами: "' . $str2 . '"<br>';   // "Hi   !"

// ---------------------------------------------------------------------
// 3. Heredoc.
// ---------------------------------------------------------------------

echo '<h3>3. Heredoc</h3>';

$title = 'PHP 8';
$html = <<<HTML
    <div class="card">
        <h2>{$title}</h2>
        <p>Многострочный текст с интерполяцией.</p>
    </div>
    HTML;

echo $html . '<br>';

// ---------------------------------------------------------------------
// 4. Nowdoc.
// ---------------------------------------------------------------------

echo '<h3>4. Nowdoc</h3>';

$sql = <<<'SQL'
    SELECT * FROM users
    WHERE name = '$name'
    SQL;

echo '<pre>' . $sql . '</pre>';   // $name не интерполируется

// ---------------------------------------------------------------------
// 5. Гибкий синтаксис (PHP 7.3+).
// ---------------------------------------------------------------------

echo '<h3>5. Гибкий синтаксис</h3>';

$flexible = <<<EOD
    Строка 1
    Строка 2
    EOD;

echo '<pre>' . $flexible . '</pre>';   // "Строка 1\nСтрока 2"

// ---------------------------------------------------------------------
// 6. Основные функции для строк.
// ---------------------------------------------------------------------

echo '<h3>6. Функции для строк</h3>';
echo '<pre>';

$text = 'Hello, World!';

printf("strlen: %d\n", strlen($text));
printf("mb_strlen: %d\n", mb_strlen($text));
printf("strpos 'World': %d\n", strpos($text, 'World'));
printf("substr(7, 5): %s\n", substr($text, 7, 5));
printf("str_replace: %s\n", str_replace('World', 'PHP', $text));
printf("trim: '%s'\n", trim('  text  '));
printf("strtolower: %s\n", strtolower($text));
printf("strtoupper: %s\n", strtoupper($text));

echo '</pre>';

// ---------------------------------------------------------------------
// 7. UTF-8: strlen vs mb_strlen.
// ---------------------------------------------------------------------

echo '<h3>7. UTF-8</h3>';
$ru = 'Привет';
echo 'strlen: ' . strlen($ru) . ' байт<br>';
echo 'mb_strlen: ' . mb_strlen($ru) . ' символов<br>';

// ---------------------------------------------------------------------
// 8. sprintf — форматирование.
// ---------------------------------------------------------------------

echo '<h3>8. sprintf</h3>';
$price = 1234.5;
echo sprintf('Цена: %.2f руб.', $price) . '<br>';   // 1234.50
echo sprintf('Код: %04d', 42) . '<br>';            // 0042

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;