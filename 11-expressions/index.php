<?php

declare(strict_types=1);

/**
 * Урок 11 — Выражения.
 *
 * Практика: присваивание как выражение, инкремент/декремент,
 * print vs echo, тернарный оператор, match, типы значений.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/11-expressions/
 */

// ---------------------------------------------------------------------
// 1. Присваивание как выражение.
// ---------------------------------------------------------------------

echo '<h3>1. Присваивание как выражение</h3>';

$a = 5;
echo '$a = ' . $a . '<br>';   // 5

$b = $a = 5;
echo '$b = ' . $b . ', $a = ' . $a . '<br>';   // 5, 5

$c = ($a = 5) + 2;
echo '$c = ' . $c . ', $a = ' . $a . '<br>';   // 7, 5

// ---------------------------------------------------------------------
// 2. Инкремент и декремент как выражения.
// ---------------------------------------------------------------------

echo '<h3>2. Инкремент и декремент</h3>';

$a = 5;
$b = $a++;
echo '$b = $a++ → $b = ' . $b . ', $a = ' . $a . '<br>';   // 5, 6

$a = 5;
$c = ++$a;
echo '$c = ++$a → $c = ' . $c . ', $a = ' . $a . '<br>';   // 6, 6

// ---------------------------------------------------------------------
// 3. print vs echo.
// ---------------------------------------------------------------------

echo '<h3>3. print vs echo</h3>';

$result = print 'Hello (print)';
echo '<br>$result = ' . $result . '<br>';   // 1

// echo не возвращает значение — раскомментируй, увидишь ошибку:
// $result = echo 'Hello (echo)';

// ---------------------------------------------------------------------
// 4. Функции как выражения.
// ---------------------------------------------------------------------

echo '<h3>4. Функции как выражения</h3>';

function add(int $a, int $b): int
{
    return $a + $b;
}

$sum = add(2, 3);
echo 'add(2, 3) = ' . $sum . '<br>';   // 5

// Функция в выражении:
$result = add(2, 3) * 2;
echo 'add(2, 3) * 2 = ' . $result . '<br>';   // 10

// ---------------------------------------------------------------------
// 5. Тернарный оператор.
// ---------------------------------------------------------------------

echo '<h3>5. Тернарный оператор</h3>';

$isPaid = true;
$status = $isPaid ? 'paid' : 'unpaid';
echo 'Статус: ' . $status . '<br>';   // paid

// ---------------------------------------------------------------------
// 6. match (PHP 8.0+).
// ---------------------------------------------------------------------

echo '<h3>6. match</h3>';

$isPaid = false;

$status = match ($isPaid) {
    true  => 'paid',
    false => 'unpaid',
};

echo 'Статус (match): ' . $status . '<br>';   // unpaid

// ---------------------------------------------------------------------
// 7. Типы значений выражений.
// ---------------------------------------------------------------------

echo '<h3>7. Типы значений</h3>';
echo '<pre>';

var_dump(5);                    // int(5)
var_dump(3.14);                 // float(3.14)
var_dump("Hello");              // string(5) "Hello"
var_dump(true);                 // bool(true)
var_dump([1, 2, 3]);            // array(3)
var_dump(null);                 // NULL
var_dump(5 > 3);                // bool(true)
var_dump(5 + 3);                // int(8)

echo '</pre>';

// ---------------------------------------------------------------------
// 8. Выражение vs оператор.
// ---------------------------------------------------------------------

echo '<h3>8. Выражение vs оператор</h3>';

// Выражение (может быть частью другого выражения):
$result = 5 + 3;

// Оператор (инструкция):
if ($result > 5) {
    echo 'Результат больше 5.<br>';
}

// Выражение как оператор:
$result + 1;   // Вычисляется, но результат нигде не используется

// ---------------------------------------------------------------------
// 9. Приоритет операторов.
// ---------------------------------------------------------------------

echo '<h3>9. Приоритет</h3>';
echo '1 + 5 * 3 = ' . (1 + 5 * 3) . '<br>';       // 16
echo '(1 + 5) * 3 = ' . ((1 + 5) * 3) . '<br>';   // 18

// ---------------------------------------------------------------------
// 10. Оператор ?? как выражение.
// ---------------------------------------------------------------------

echo '<h3>10. Оператор ??</h3>';

$username = $_GET['user'] ?? 'guest';
echo 'username: ' . $username . '<br>';   // guest

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;