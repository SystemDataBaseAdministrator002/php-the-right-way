<?php

declare(strict_types=1);

/**
 * Урок 13 — Операторы (часть 2).
 *
 * Практика: @, инкремент/декремент, логические, побитовые,
 * операторы массивов, оператор исполнения.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/13-operators-p2/
 */

// ---------------------------------------------------------------------
// 1. Оператор контроля ошибок @.
// ---------------------------------------------------------------------

echo '<h3>1. Оператор @</h3>';

$value = @file_get_contents('nonexistent.txt');
var_dump($value);   // bool(false) без Warning
echo '<br>';

// @ не подавляет фатальные ошибки — раскомментируй, увидишь Fatal error:
// @undefinedFunction();

// ---------------------------------------------------------------------
// 2. Инкремент и декремент.
// ---------------------------------------------------------------------

echo '<h3>2. Инкремент и декремент</h3>';
echo '<pre>';

$a = 5;
$b = $a++;
echo "\$b = \$a++ → \$b = $b, \$a = $a\n";   // 5, 6

$a = 5;
$c = ++$a;
echo "\$c = ++\$a → \$c = $c, \$a = $a\n";   // 6, 6

// Строки.
$s = 'a';
$s++;
echo "Строка 'a'++ → '$s'\n";   // 'b'

$s = 'b';
$s--;
echo "Строка 'b'-- → '$s'\n";   // 'b' (без изменений)

// null.
$n = null;
$n++;
echo "null++ → $n\n";   // 1

$n = null;
$n--;
var_dump($n);   // NULL

// bool.
$b = true;
$b++;
var_dump($b);   // bool(true)

echo '</pre>';

// ---------------------------------------------------------------------
// 3. Логические операторы.
// ---------------------------------------------------------------------

echo '<h3>3. Логические</h3>';
echo '<pre>';

var_dump(true && false);   // false
var_dump(true || false);   // true
var_dump(!true);           // false

var_dump(true and false);  // false
var_dump(true or false);   // true
var_dump(true xor true);   // false
var_dump(true xor false);  // true

// Приоритет.
$res1 = true && false;
$res2 = true and false;
var_dump($res1);   // false
var_dump($res2);   // true

// Короткое замыкание.
function check(): bool
{
    echo 'Вызвана!<br>';
    return true;
}

false && check();   // check() не вызовется
true || check();    // check() не вызовется

echo '</pre>';

// ---------------------------------------------------------------------
// 4. Побитовые операторы.
// ---------------------------------------------------------------------

echo '<h3>4. Побитовые</h3>';
echo '<pre>';

var_dump(5 & 3);    // int(1)
var_dump(5 | 3);    // int(7)
var_dump(5 ^ 3);    // int(6)
var_dump(~5);       // int(-6)
var_dump(5 << 1);   // int(10)
var_dump(5 >> 1);   // int(2)

echo '</pre>';

// ---------------------------------------------------------------------
// 5. Операторы массивов.
// ---------------------------------------------------------------------

echo '<h3>5. Операторы массивов</h3>';
echo '<pre>';

$a = ['x' => 1, 'y' => 2];
$b = ['y' => 3, 'z' => 4];

var_dump($a + $b);   // ['x' => 1, 'y' => 2, 'z' => 4]

var_dump([1, 2] == [1, 2]);     // true
var_dump([1, 2] === [1, 2]);    // true
var_dump([1, 2] === ['1', '2']); // false
var_dump([1, 2] === [2, 1]);    // false

echo '</pre>';

// ---------------------------------------------------------------------
// 6. Оператор исполнения (backticks).
// ---------------------------------------------------------------------

echo '<h3>6. Оператор исполнения</h3>';

if (function_exists('shell_exec')) {
    $output = `echo "Hello from shell"`;
    echo 'Вывод: ' . $output . '<br>';
} else {
    echo 'shell_exec отключён.<br>';
}

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;