<?php

declare(strict_types=1);

/**
 * Урок 10 — Массивы.
 *
 * Практика: создание, доступ, операции, ассоциативные,
 * многомерные, деструктуризация, spread, функции.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/10-array/
 */

// ---------------------------------------------------------------------
// 1. Создание массивов.
// ---------------------------------------------------------------------

echo '<h3>1. Создание</h3>';

$fruits = ['apple', 'banana', 'cherry'];
$user = ['name' => 'Gio', 'age' => 30];

echo '<pre>';
print_r($fruits);
print_r($user);
echo '</pre>';

// ---------------------------------------------------------------------
// 2. Доступ к элементам.
// ---------------------------------------------------------------------

echo '<h3>2. Доступ</h3>';
echo $fruits[0] . '<br>';      // apple
echo $user['name'] . '<br>';   // Gio

// ---------------------------------------------------------------------
// 3. Операции.
// ---------------------------------------------------------------------

echo '<h3>3. Операции</h3>';

$arr = [1, 2, 3];

$arr[] = 4;                    // [1, 2, 3, 4]
array_push($arr, 5, 6);        // [1, 2, 3, 4, 5, 6]
array_unshift($arr, 0);        // [0, 1, 2, 3, 4, 5, 6]

echo 'После добавления: ';
print_r($arr);

array_pop($arr);               // Удаляет 6
array_shift($arr);             // Удаляет 0
unset($arr[1]);                // Удаляет по ключу 1

echo '<br>После удаления: ';
print_r($arr);
echo '<br>';

// ---------------------------------------------------------------------
// 4. Проверка существования.
// ---------------------------------------------------------------------

echo '<h3>4. Проверка</h3>';
echo '<pre>';

$data = ['key' => null];

var_dump(isset($data['key']));           // false
var_dump(array_key_exists('key', $data)); // true
var_dump(isset($data['missing']));        // false

echo '</pre>';

// ---------------------------------------------------------------------
// 5. Многомерные массивы.
// ---------------------------------------------------------------------

echo '<h3>5. Многомерные</h3>';

$users = [
    'admin' => [
        'name' => 'Иван',
        'age' => 30
    ],
    'moderator' => [
        'name' => 'Мария',
        'age' => 25
    ]
];

echo $users['admin']['name'] . '<br>';      // Иван
echo $users['moderator']['age'] . '<br>';   // 25

// Безопасный доступ.
echo ($users['guest']['name'] ?? 'Пользователь не найден') . '<br>';

// ---------------------------------------------------------------------
// 6. Деструктуризация.
// ---------------------------------------------------------------------

echo '<h3>6. Деструктуризация</h3>';

[$first, $second] = [1, 2];
echo "first: $first, second: $second<br>";

[,, $third] = [1, 2, 3];
echo "third: $third<br>";

['name' => $name, 'age' => $age] = ['name' => 'Gio', 'age' => 30];
echo "name: $name, age: $age<br>";

// ---------------------------------------------------------------------
// 7. Spread оператор.
// ---------------------------------------------------------------------

echo '<h3>7. Spread</h3>';

$a = [1, 2];
$b = [3, 4];
$merged = [...$a, ...$b];
echo '<pre>';
print_r($merged);
echo '</pre>';

// Строковые ключи (PHP 8.1+).
$c = [...['a' => 1], ...['a' => 2, 'b' => 3]];
echo '<pre>';
print_r($c);   // ['a' => 2, 'b' => 3]
echo '</pre>';

// ---------------------------------------------------------------------
// 8. Функции высшего порядка.
// ---------------------------------------------------------------------

echo '<h3>8. Функции</h3>';

$numbers = [1, 2, 3, 4, 5];

$squared = array_map(fn($n) => $n * $n, $numbers);
$even = array_filter($numbers, fn($n) => $n % 2 === 0);
$sum = array_reduce($numbers, fn($carry, $n) => $carry + $n, 0);

echo 'squared: ' . implode(', ', $squared) . '<br>';   // 1, 4, 9, 16, 25
echo 'even: ' . implode(', ', $even) . '<br>';         // 2, 4
echo 'sum: ' . $sum . '<br>';                          // 15

// ---------------------------------------------------------------------
// 9. count().
// ---------------------------------------------------------------------

echo '<h3>9. count()</h3>';

$nested = [1, [2, 3], [4, [5, 6]]];
echo 'count: ' . count($nested) . '<br>';                     // 3
echo 'count recursive: ' . count($nested, COUNT_RECURSIVE) . '<br>';   // 8

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;