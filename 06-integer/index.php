<?php

declare(strict_types=1);

/**
 * Урок 06 — Целые числа (Integer).
 *
 * Практика: создание int, системы счисления, переполнение,
 * приведение типов, is_int, intval, подчёркивания.
 *
 * Открой в браузере:
 * http://localhost/php-the-right-way/06-integer/
 */

// ---------------------------------------------------------------------
// 1. Создание целых чисел.
// ---------------------------------------------------------------------

$decimal = 1234;
$negative = -567;
$zero = 0;

echo '<h3>1. Создание int</h3>';
var_dump($decimal, $negative, $zero);
echo '<br>';

// ---------------------------------------------------------------------
// 2. Системы счисления.
// ---------------------------------------------------------------------

$hex = 0x1A;        // 26
$octal = 0123;      // 83
$octalNew = 0o123;  // 83 (PHP 8.1+)
$binary = 0b11111111; // 255

echo '<h3>2. Системы счисления</h3>';
echo '0x1A = ' . $hex . '<br>';
echo '0123 = ' . $octal . '<br>';
echo '0o123 = ' . $octalNew . '<br>';
echo '0b11111111 = ' . $binary . '<br>';

// ---------------------------------------------------------------------
// 3. Константы диапазона.
// ---------------------------------------------------------------------

echo '<h3>3. Диапазон</h3>';
echo 'PHP_INT_MAX = ' . PHP_INT_MAX . '<br>';
echo 'PHP_INT_MIN = ' . PHP_INT_MIN . '<br>';
echo 'PHP_INT_SIZE = ' . PHP_INT_SIZE . ' байт<br>';

// ---------------------------------------------------------------------
// 4. Переполнение.
// ---------------------------------------------------------------------

echo '<h3>4. Переполнение</h3>';
var_dump(PHP_INT_MAX + 1);   // float
echo '<br>';

// ---------------------------------------------------------------------
// 5. Приведение к int.
// ---------------------------------------------------------------------

echo '<h3>5. Приведение к int</h3>';
echo '<pre>';

var_dump((int) true);        // int(1)
var_dump((int) false);       // int(0)
var_dump((int) 5.98);        // int(5)
var_dump((int) -5.98);       // int(-5)
var_dump((int) "5.9");       // int(5)
var_dump((int) "87abc");     // int(87)
var_dump((int) "abc");       // int(0)
var_dump((int) null);        // int(0)

echo '</pre>';

// ---------------------------------------------------------------------
// 6. Проверка типа.
// ---------------------------------------------------------------------

echo '<h3>6. is_int / is_integer / is_long</h3>';
var_dump(is_int(42));        // true
var_dump(is_int("42"));      // false
var_dump(is_integer(42));    // true
var_dump(is_long(42));       // true
echo '<br>';

// ---------------------------------------------------------------------
// 7. intval с base.
// ---------------------------------------------------------------------

echo '<h3>7. intval с base</h3>';
echo 'intval("FF", 16) = ' . intval('FF', 16) . '<br>';   // 255
echo 'intval("777", 8) = ' . intval('777', 8) . '<br>';   // 511
echo 'intval("1010", 2) = ' . intval('1010', 2) . '<br>'; // 10

// ---------------------------------------------------------------------
// 8. Подчёркивания.
// ---------------------------------------------------------------------

echo '<h3>8. Подчёркивания</h3>';
$million = 1_000_000;
var_dump($million);              // int(1000000)
var_dump((int) "1_000_000");     // int(1)

// ---------------------------------------------------------------------
// 9. Арифметика и тип результата.
// ---------------------------------------------------------------------

echo '<h3>9. Арифметика</h3>';
echo '<pre>';
var_dump(4 * 2.5);    // float(10)
var_dump(10 / 2);     // int(5)
var_dump(10 / 3);     // float(3.333...)
echo '</pre>';

// ---------------------------------------------------------------------
// 10. filter_var для валидации.
// ---------------------------------------------------------------------

echo '<h3>10. filter_var</h3>';
var_dump(filter_var('123', FILTER_VALIDATE_INT));      // int(123)
var_dump(filter_var('123abc', FILTER_VALIDATE_INT));   // false
var_dump(filter_var('abc', FILTER_VALIDATE_INT));      // false

echo '<hr>';
echo 'Версия PHP: ' . PHP_VERSION;